#!/usr/bin/env bash
# Checks this repository's capability map: every capability heading is a
# lowercase-kebab id under a context, every entry has the fields below in this
# order, the capability table in the agent instructions matches the map, and,
# when a glossary is configured, every glossary term is spoken by some
# capability or declared as not built. Installed by the capability-map skill,
# whose tests cover every rule here. Needs bash and a POSIX awk; runs on
# bash 3.2 (macOS) and mawk (Ubuntu) too.
#
#   scripts/capability-map.sh         check
#   scripts/capability-map.sh --fix   regenerate the table, then check
#
# The awk programs are single-quoted on purpose: bash must not expand them.
# shellcheck disable=SC2016
set -euo pipefail
export LC_ALL=C

# The map, and the file that holds the generated table. Both relative to the
# repository root.
MAP='docs/capability-map.md'
AGENT_FILE='CLAUDE.md'

# The fields every entry has, in order, separated by "|".
FIELDS='One line|Language|Owns|Contracts|Who acts|Is not|Lives in|Decisions|State'

# Top-level sections of the map that hold no capabilities.
CLOSING='Declared, not built|Where the words still disagree|Seams worth knowing|How to keep this page true'

# The glossary: a file and the heading of its section, with entries written as
# "- **Term** — definition". Leave GLOSSARY_FILE empty to skip the check.
GLOSSARY_FILE=''
GLOSSARY_HEADING='## Glossary'

BEGIN_MARK='<!-- BEGIN GENERATED by capability-map.sh: do not edit; change the map, then run it with --fix -->'
END_MARK='<!-- END GENERATED by capability-map.sh -->'

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)
root=$(git -C "$here" rev-parse --show-toplevel 2>/dev/null) || root=$(cd "$here/.." && pwd -P)
script=${here#"$root"/}/$(basename "${BASH_SOURCE[0]}")
cd "$root"

fix=0
case "${1:-}" in
'') ;;
--fix) fix=1 ;;
*)
  echo "usage: $script [--fix]" >&2
  exit 2
  ;;
esac

if [ ! -f "$MAP" ]; then
  echo "$MAP: not found" >&2
  exit 1
fi
if [ ! -f "$AGENT_FILE" ]; then
  echo "$AGENT_FILE: not found" >&2
  exit 1
fi

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
: >"$work/violations"

# Read the map once. Prints, tab-separated:
#   ROW   <id> <context> <one line>
#   LANG  <language line>
#   DECL  <a line of the "Declared, not built" section>
#   ERR   <violation>
awk -v map="$MAP" -v fields="$FIELDS" -v closing="$CLOSING" '
function reset() { id = ""; one = ""; count = 0; split("", seen) }
function flush(   i, last) {
  if (id == "") return
  last = 0
  for (i = 1; i <= n; i++) {
    if (!(F[i] in seen)) { print "ERR\t" map ": " id ": no **" F[i] ":** line"; continue }
    if (seen[F[i]] < last) print "ERR\t" map ": " id ": **" F[i] ":** is out of order"
    if (seen[F[i]] > last) last = seen[F[i]]
  }
  if (one == "") print "ERR\t" map ": " id ": **One line:** is empty"
  print "ROW\t" id "\t" context "\t" one
  reset()
}
BEGIN {
  n = split(fields, F, "|")
  for (i = 1; i <= n; i++) known[F[i]] = 1
  m = split(closing, C, "|")
  for (i = 1; i <= m; i++) closed[C[i]] = 1
  reset(); context = ""; inclosing = 0; fence = 0
}
/^```/ { fence = !fence; next }
fence { next }
/^# / {
  flush(); context = substr($0, 3); inclosing = (context in closed)
  declared = (context == "Declared, not built")
  next
}
/^---[ \t]*$/ { flush(); inclosing = 1; declared = 0; next }
/^## / {
  flush()
  if (inclosing) next
  id = substr($0, 4)
  if (id !~ /^[a-z][a-z0-9-]*$/) print "ERR\t" map ": \"## " id "\" is not a capability id; write it in lowercase-kebab-case"
  if (context == "") print "ERR\t" map ": " id ": no context (\"# \" heading) above it"
  next
}
declared && NF { print "DECL\t" $0 }
id != "" && /^\*\*[^*]+:\*\*/ {
  f = $0; sub(/^\*\*/, "", f); sub(/:\*\*.*$/, "", f)
  if (!(f in known)) { print "ERR\t" map ": " id ": **" f ":** is not a field of the template"; next }
  if (f in seen) print "ERR\t" map ": " id ": **" f ":** appears twice"
  seen[f] = ++count
  value = $0; sub(/^\*\*[^*]+:\*\*[ \t]*/, "", value)
  if (f == "One line") one = value
  if (f == "Language") print "LANG\t" value
}
END { flush() }
' "$MAP" >"$work/map"

grep '^ERR' "$work/map" | cut -f2- >>"$work/violations" || true

# The table, generated from the rows.
{
  echo '| Capability | Context | What it is |'
  echo '| --- | --- | --- |'
  awk -F '\t' -v map="$MAP" '
    $1 == "ROW" { one = $4; gsub(/\|/, "\\|", one); print "| [" $2 "](" map "#" $2 ") | " $3 " | " one " |" }
  ' "$work/map"
} >"$work/table"

if ! grep -qF -- "$BEGIN_MARK" "$AGENT_FILE" || ! grep -qF -- "$END_MARK" "$AGENT_FILE"; then
  echo "$AGENT_FILE: the generated-table markers are missing; add them where the table goes, then run $script --fix" >>"$work/violations"
else
  awk -v begin="$BEGIN_MARK" -v end="$END_MARK" -v table="$work/table" '
    $0 == begin { print; while ((getline line < table) > 0) print line; skip = 1; next }
    $0 == end { skip = 0 }
    !skip { print }
  ' "$AGENT_FILE" >"$work/agent"
  if ! cmp -s "$work/agent" "$AGENT_FILE"; then
    if [ "$fix" -eq 1 ]; then
      cat "$work/agent" >"$AGENT_FILE"
      echo "$AGENT_FILE: capability table regenerated"
    else
      echo "$AGENT_FILE: the capability table is stale; run $script --fix" >>"$work/violations"
    fi
  fi
fi

# Every glossary term is spoken by some capability, or declared as not built.
if [ -n "$GLOSSARY_FILE" ]; then
  if [ ! -f "$GLOSSARY_FILE" ]; then
    echo "$GLOSSARY_FILE: not found (GLOSSARY_FILE in $script)" >>"$work/violations"
  else
    awk -F '\t' '$1 == "LANG" || $1 == "DECL" { print tolower($2) }' "$work/map" >"$work/spoken"
    awk -v heading="$GLOSSARY_HEADING" '
      $0 == heading { inside = 1; next }
      inside && /^#/ { exit }
      inside && /^- \*\*[^*]+\*\*/ { t = $0; sub(/^- \*\*/, "", t); sub(/\*\*.*$/, "", t); print t }
    ' "$GLOSSARY_FILE" >"$work/terms"
    if [ ! -s "$work/terms" ]; then
      echo "$GLOSSARY_FILE: no \"- **Term**\" entries under \"$GLOSSARY_HEADING\"" >>"$work/violations"
    fi
    while IFS= read -r term; do
      lower=$(printf '%s' "$term" | tr '[:upper:]' '[:lower:]')
      if ! grep -qF -- "$lower" "$work/spoken"; then
        echo "$GLOSSARY_FILE: \"$term\" is spoken by no capability; add it to a **Language:** line, or list it under \"Declared, not built\"" >>"$work/violations"
      fi
    done <"$work/terms"
  fi
fi

if [ -s "$work/violations" ]; then
  cat "$work/violations" >&2
  echo "capability map: $(wc -l <"$work/violations" | tr -d ' ') violation(s)" >&2
  exit 1
fi
echo "capability map: $(grep -c '^ROW' "$work/map") capabilities, all good"
